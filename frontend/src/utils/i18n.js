/**
 * Helper to fetch a localized string. Falls back to English if key/language missing.
 */
export function t(key, lang = 'en') {
  const effectiveLang = (lang && I18N_STRINGS[key]?.[lang]) ? lang : 'en';
  return I18N_STRINGS[key]?.[effectiveLang] || I18N_STRINGS[key]?.en || key;
}

/**
 * Returns localized category label.
 */
export function getLocalizedCategory(cat, lang = 'en') {
  if (!cat) return '';
  const c = String(cat).toLowerCase();
  if (c.includes('agri') || c.includes('farmer') || c.includes('rural')) return t('cat_agriculture', lang);
  if (c.includes('edu') || c.includes('student') || c.includes('scholarship')) return t('cat_education', lang);
  if (c.includes('business') || c.includes('loan') || c.includes('credit') || c.includes('bank') || c.includes('entrepreneur')) return t('cat_business', lang);
  if (c.includes('health') || c.includes('medical') || c.includes('hospital')) return t('cat_health', lang);
  if (c.includes('energy') || c.includes('solar') || c.includes('power')) return t('cat_energy', lang);
  if (c.includes('welfare') || c.includes('social') || c.includes('pension') || c.includes('empower')) return t('cat_pension', lang);
  return cat;
}

/**
 * Returns the BCP-47 speech recognition tag for a given language code.
 */
export function getSpeechLangTag(lang = 'auto') {
  const match = SUPPORTED_LANGUAGES.find(l => l.code === lang);
  return match?.bcp47 || 'hi-IN';
}
